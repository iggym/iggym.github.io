// Writes sw.js: a service worker that precaches the site shell (pages, styles, scripts, fonts, icons)
// and caches images the first time they are viewed, so a first visit stays light on mobile.
// The cache name is a hash of the precached files, so any content change installs a fresh cache.
// Run from the repo root after any change: node scripts/build-sw.mjs
// Check only (fails if sw.js is stale): node scripts/build-sw.mjs --check
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKIP = new Set(['.git', 'node_modules', 'tests', 'tasks', 'scripts', 'resume']);
const INCLUDE = new Set(['.html', '.css', '.js', '.woff2', '.jpg', '.png', '.svg', '.webp', '.webmanifest', '.xml', '.json']);

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP.has(name) || name.startsWith('.')) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (INCLUDE.has(extname(p)) && name !== 'sw.js') out.push(relative(root, p).split('\\').join('/'));
  }
  return out;
}

const files = walk(root).sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 12);
// Precache URLs are site-root paths, plus the site root itself.
// Images (except the small icons) are cached on first view instead of up front.
const SHELL = (f) => !/\.(jpg|png|webp)$/.test(f) || /^assets\/img\/icon-/.test(f);
const urls = ['/', ...files.filter(SHELL).map((f) => '/' + f)];
// Top-level paths that belong to this site. Every other path on iggym.github.io is a separate
// project site (iggym.github.io/<repo>/), which this worker must never intercept.
const own = new Set(['/']);
for (const f of files) own.add('/' + (f.includes('/') ? f.split('/')[0] + '/' : f));
own.add('/sw.js');
const OWN = [...own].sort();

const sw = `// Generated by scripts/build-sw.mjs. Do not edit by hand.
const CACHE = "iggym-${version}";
const PRECACHE = ${JSON.stringify(urls, null, 2)};
const OWN = ${JSON.stringify(OWN)};
const isOwn = (p) => p === "/" || OWN.some((o) => o !== "/" && (o.endsWith("/") ? p.startsWith(o) : p === o));

self.addEventListener("install", (event) => {
  // cache: "reload" skips the browser's HTTP cache so a new version never precaches stale files.
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((u) => new Request(u, { cache: "reload" }))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names.filter((n) => n.startsWith("iggym-") && n !== CACHE).map((n) => caches.delete(n))))
      .then(() => self.clients.claim())
  );
});

// Pages, styles, scripts and data: network first, so a deploy shows up on the next load.
// The cached copy is the offline fallback. Fonts and images: cache first, they rarely change.
const FRESH = /\.(html|css|js|json|xml|webmanifest)$/;

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  // Only same-origin requests. Outside services (AI providers, the Worker, analytics) always go to the network.
  if (url.origin !== self.location.origin) return;
  // Other project sites share this origin (iggym.github.io/<repo>/). Leave them alone.
  if (!isOwn(url.pathname)) return;
  const isPage = req.mode === "navigate";
  if (isPage || url.pathname.endsWith("/") || FRESH.test(url.pathname)) {
    event.respondWith(
      fetch(isPage ? new Request(req, { cache: "no-cache" }) : req)
        .then((res) => {
          if (res.ok && res.type === "basic") {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(url.pathname, copy)).catch(() => {});
          }
          return res;
        })
        .catch(() =>
          caches.match(url.pathname, { ignoreSearch: true }).then((hit) =>
            hit || (isPage ? caches.match("/404.html") : Response.error())
          )
        )
    );
    return;
  }
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
      // Cache fonts and images the first time they load, for the next visit and offline use.
      if (res.ok && res.type === "basic") {
        const copy = res.clone();
        caches.open(CACHE).then((cache) => cache.put(url.pathname, copy)).catch(() => {});
      }
      return res;
    }))
  );
});
`;
const target = join(root, 'sw.js');
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== sw) {
    console.error('sw.js is stale. Run: node scripts/build-sw.mjs');
    process.exit(1);
  }
  console.log('sw.js is up to date.');
} else {
  writeFileSync(target, sw, 'utf8');
  console.log(`wrote sw.js: cache iggym-${version}, ${urls.length} precached URLs`);
}
